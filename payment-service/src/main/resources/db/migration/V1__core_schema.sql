-- worth more than getting the boundary right by luck on day one.
-- =============================================================================================

-- ---------------------------------------------------------------------------------------------
-- processed_events - how a consumer stays idempotent (Phase 4, owned by ledger-service).
--
-- Kafka gives you at-least-once delivery: after a rebalance or a crash between processing and
-- offset commit, the same event arrives again. The consumer records the event id here inside the
-- SAME transaction that writes the ledger entries, so the second delivery hits this primary key,
-- rolls back, and posts nothing. At-least-once transport plus this table equals exactly-once
-- BUSINESS EFFECTS - which is the only kind of exactly-once anyone can honestly claim.
-- ---------------------------------------------------------------------------------------------
CREATE TABLE processed_events (
    event_id     UUID        PRIMARY KEY,             -- the outbox_events.id, carried in the message
    consumer     VARCHAR(64) NOT NULL,                -- which consumer group processed it
    processed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------------------------
-- ledger_entries - double-entry, append-only (Phase 4, owned by ledger-service).
--
-- Every money movement is at least two rows: one debit and one credit, with equal magnitude, in
-- the same transaction, sharing a transaction_ref. For a capture:
--     DEBIT  customer_receivable   12500 INR
--     CREDIT merchant_payable      12500 INR
-- and a refund posts the mirror image. The invariant the tests assert is simply
--     SUM(amount_minor) FILTER (WHERE direction='DEBIT')
--   = SUM(amount_minor) FILTER (WHERE direction='CREDIT')
-- for every transaction_ref, and globally.
--
-- Append-only means exactly that: corrections are new reversing entries, never UPDATE or DELETE.
-- An audit trail you can edit is not an audit trail. Enforce it in Phase 4 by granting the
-- application role only INSERT and SELECT on this table - a comment is a wish, a GRANT is a rule.
-- ---------------------------------------------------------------------------------------------
CREATE TABLE ledger_entries (
    id              UUID         PRIMARY KEY,
    -- Groups the two (or more) sides of one movement. The balance invariant is checked per ref.
    transaction_ref UUID         NOT NULL,
    payment_id      UUID         NOT NULL,
    -- Chart of accounts, kept deliberately tiny: CUSTOMER_RECEIVABLE, MERCHANT_PAYABLE,
    -- PLATFORM_FEE. Three accounts are enough to demonstrate double entry; thirty would be a
    -- different project.
    account         VARCHAR(64)  NOT NULL,
    direction       VARCHAR(6)   NOT NULL,
    amount_minor    BIGINT       NOT NULL,
    currency        CHAR(3)      NOT NULL,
    -- The event that produced this line, for tracing a ledger row back to its cause.
    event_id        UUID         NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ledger_direction_known CHECK (direction IN ('DEBIT', 'CREDIT')),
    -- Amounts are always positive; the sign lives in `direction`. Allowing negative amounts means
    -- there are two ways to express the same movement, and two ways to express one thing is one
    -- way too many in a ledger.
    CONSTRAINT ledger_amount_positive CHECK (amount_minor > 0)
);

CREATE INDEX idx_ledger_payment ON ledger_entries (payment_id);
CREATE INDEX idx_ledger_transaction ON ledger_entries (transaction_ref);
CREATE UNIQUE INDEX uq_ledger_event_account_direction
    ON ledger_entries (event_id, account, direction);
COMMENT ON INDEX uq_ledger_event_account_direction IS
    'Belt and braces with processed_events: even if the idempotency check is bypassed, one event
     cannot post the same account/direction line twice.';
